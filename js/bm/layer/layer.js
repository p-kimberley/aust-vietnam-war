/**
 * Generates the UI for layers as they are added to groups within the controller. Can serialise layer state and allows for
 * layers to be shown/hidden
 * @param containerElement
 * @constructor
 * @class
 */
BM.LayerController = function(containerElement)
{
	this.containerElement = containerElement;                   // jQuery object for containing all UI elements generated by the LayerController
	this.initInProgress = false;                                // Set during initialisation. Stops multiple replaceState calls from occurring

	if (!containerElement)
		console.log('Error: BM.LayerController was provided an invalid container element');

	this.layerGroups = [];
};

/**
 * Creates a new layer group and adds it to the controller
 * @param {BM.LayerGroup} layerGroup - The initialised layer group object to add to the controller
 * @returns {BM.LayerGroup}
 */
BM.LayerController.prototype.addGroup = function(layerGroup)
{
	this.layerGroups.push(layerGroup);
	this.containerElement.append(layerGroup.selectorControlContainer);
	BM.initICheckUIControl(layerGroup.selectorControl);
	layerGroup.layerController = this;

	return layerGroup;
};

