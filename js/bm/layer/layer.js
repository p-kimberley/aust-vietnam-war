/**
 * Layer class encapsulating a LeafletJS layer and properties allowing its visibility to be changed via the UI
 * @param {BM.LayerType} type - LayerType unique descriptor, allowing the layer to be referenced
 * @param {string} title - Label to display for the layer's checkbox
 * @param {number} [zIndex] - Z order relative to the group
 * @param {{}} [layerOptions] - User-configurable options for the layer
 * @constructor
 * @class
 */
BM.Layer = function(type, title, zIndex, layerOptions)
{
	var self = this;
	this.olLayer = null;                           // Initialised and generated by external function at 'layerGenerationFn'
	this.type = type;
	this.title = title;                            // Title used to describe the layer in the UI
	this.zIndex = zIndex;
	this.parentGroup = null;
	this.generationInProgress = false;
	this.silentRegeneration = false;				// If TRUE, regeneration is performed without any progress feedback

	/**
	 * Common properties that are added to olLayer after initialisation.
	 * Subclasses should add/change these properties as required.
	 * @type {{}}
	 */
	this.layerProperties = {};

	/**
	 * User customisation controls that are defined by subclasses prior to invoking BM.Layer constructor
	 * @type {{BM.LayerOption}}
	 */
	this.layerOptions = layerOptions || {};
	this.layerOptions.opacity = new BM.LayerOption.Slider('Opacity', {
		min: 1,
		max: 100,
		onChange: function(oldValue, newValue) {
			if (self.olLayer)
				self.olLayer.setOpacity(newValue / 100);
		}
	});

	var layerControlID = 'layer-' + this.type;
	this.selectorControlContainer = $(document.createElement('div'));
	this.selectorControl = $(document.createElement('input'))
		.addClass('layer-selector-control')
		.attr('id', layerControlID)
		.appendTo(this.selectorControlContainer);
	$(document.createElement('label'))
		.addClass('layer-selector-control')
		.attr('for', layerControlID)
		.text(self.title)
		.appendTo(this.selectorControlContainer);

	if (this.layerOptions)
	{
		this.optionContainer = $(document.createElement('div'))
			.addClass('layer-option-container')
			.appendTo(this.selectorControlContainer);
		this.optionTooltip = $(document.createElement('div'))
			.addClass('layer-options-tooltip-content')
			.appendTo(this.optionContainer);
		this.optionButton = $(document.createElement('div'))
			.addClass('button')
			.append('<span class="fa fa-cog"></span>')
			.appendTo(this.optionContainer)
			.tooltipster({
				content: this.optionTooltip,
				contentCloning: false,
				interactive: true,
				side: 'left',
				distance: 0,
				minWidth: 200,
				theme: 'tooltipster-light battlemap-tooltip-light layer-options-tooltip',
				trigger: 'custom',
				triggerOpen: 'custom',
				triggerClose: 'custom'
			})
			.click(function() {
				if ($(this).hasClass('active'))
					self.setOptionsVisibility(false);
				else
					self.setOptionsVisibility(true);
			});

		// Close the tooltip if the right sidebar is closed or the sidebar panel is changed
		$('body').on('bm:right-sidebar.visibilityChanged, bm:right-sidebar-panel.show, bm:right-sidebar-panel.hide', function(event) {
			self.setOptionsVisibility(false);
		});

		if (!this.isChecked())
			this.optionButton.hide();

		// For each layer option control, render it within the tooltip container
		for (var key in this.layerOptions)
		{
			this.layerOptions[key].render(self.optionTooltip);
		}
	}
};

/**
 * Opens or closes the layer options tooltip
 * @param {boolean} visible
 */
BM.Layer.prototype.setOptionsVisibility = function(visible)
{
	if (visible)
	{
		// Close any other open layer option tooltips
		$('.layer-option-container').find('.button')
			.removeClass('active')
			.tooltipster('close');

		this.optionButton.tooltipster('open');
		this.optionButton.addClass('active');
	}
	else
	{
		this.optionButton.tooltipster('close');
		this.optionButton.removeClass('active');
	}
};

/**
 * Prototype method to generate the layer. This could involve connecting to a tile source or creating markers based on an AJAX query.
 * To be implemented by derived classes.
 * @param [callback]
 * @abstract
 */
BM.Layer.prototype.generate = function(callback) {};

/**
 * Regenerates the layer. This is used as the public interface method to perform layer generation
 * @param [callback]
 * @param {boolean} [closeLoadingIndicatorWhenDone] - If this layer is being regenerated along with all other layers, do not close the indicator between each layer regeneration
 */
BM.Layer.prototype.regenerate = function(callback, closeLoadingIndicatorWhenDone)
{
	var self = this;
	var regenerationCompleted = function() {
		if (callback)
			callback();
	};

	// Generate if the layer selector is checked or init is in progress
	if ((this.isChecked() || this.parentGroup.layerController.initInProgress) && !this.generationInProgress)
	{
		var generate = function() {
			self.generationInProgress = true;
			self.generate(function() {
				self.generationInProgress = false;
				if (!BM.StateManagement.stateRestorationInProgress())
				{
					if (closeLoadingIndicatorWhenDone)
						BM.LoadingProgress.hide(regenerationCompleted);
					else
						regenerationCompleted();
				}
				else
				{
					regenerationCompleted();
				}
			});
		};

		if (!this.silentRegeneration)
		{
			BM.LoadingProgress.init('Generating layer', this.parentGroup.title + ' | ' + this.title, true);
			BM.LoadingProgress.show(function () {
				generate();
			});
		}
		else
		{
			generate();
		}
	}
	else
	{
		regenerationCompleted();
	}
};

BM.Layer.prototype.stateChanged = function()
{
	// TODO: This is not being fired when the group state is changed. Fix by making layers/groups event-driven

	// State changes are handled by LayerController.restoreState() during initialisation
	if (!this.parentGroup.layerController.initInProgress)
	{
		if (this.isChecked())
			this.addToMap(true);
		else
			this.removeFromMap();

		BM.StateManagement.replaceState();
	}

	if (this.optionButton)
	{
		if (this.isChecked())
		{
			this.optionButton.show();
		}
		else
		{
			this.optionButton.hide();
			this.setOptionsVisibility(false);
		}
	}
};

