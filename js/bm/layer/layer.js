/**
 * Returns a LayerGroup from its group type
 * @param {BM.LayerGroupType} groupType
 * @returns {BM.LayerGroup}
 */
BM.LayerController.prototype.getGroup = function(groupType)
{
	for(var i = 0; i < this.layerGroups.length; i++)
	{
		var group = this.layerGroups[i];
		if (group.layerGroupType === groupType)
			return group;
	}

	console.log('Warning: LayerController.getGroup could not find the layer group "' + groupType + '"');
	return null;
};

/**
 * Retrieves a BM.Layer by its LayerType
 * @param {BM.LayerType} layerType
 * @returns {BM.Layer}
 */
BM.LayerController.prototype.getLayer = function(layerType)
{
	for(var i = 0; i < this.layerGroups.length; i++)
	{
		var group = this.layerGroups[i];
		for(var j = 0; j < group.layers.length; j++)
		{
			var layer = group.layers[j];
			if (layer.type === layerType)
				return layer;
		}
	}

	return null;
};

/**
 * Refreshes the selected layer in a single-choice group (must have LayerGroup.allowMultipleActiveLayers set to FALSE.
 * Method returns NULL if this property is TRUE (i.e. checkbox groups)
 * @param {BM.LayerType} groupType
 * @returns {BM.Layer}
 */
BM.LayerController.prototype.getSelectedLayerInGroup = function(groupType)
{
	var group = this.getGroup(groupType);
	if (group)
	{
		if (group.isChecked() && !group.allowMultipleActiveLayers)
		{
			for (var i = 0; i < group.layers.length; i++)
			{
				var layer = group.layers[i];
				if (layer.isChecked())
				{
					return layer;
				}
			}

		}
	}

	return null;
};

/**
 * Creates a comma-separated list string containing the layer types that are currently selected (enabled)
 * @returns {string}
 */
BM.LayerController.prototype.serialiseState = function()
{
	var serialisedState = "";
	for(var i = 0; i < this.layerGroups.length; i++)
	{
		var group = this.layerGroups[i];

		// Group is selected, so process its contained layers
		if (group.isChecked())
		{
			for (var j = 0; j < group.layers.length; j++)
			{
				var layer = group.layers[j];

				// Layer is checked, so add its type to the serialised string
				if (layer.isChecked())
					serialisedState += (serialisedState.length > 0 ? ',' : '') + layer.type;
			}
		}
	}

	return serialisedState;
};

/**
 * Restores layer state from a serialised string containing comma-separated layer types
 * @param {string} serialisedState
 * @param callback - Invoked with the number of layers successfully processed
 */
BM.LayerController.prototype.parseState = function(serialisedState, callback)
{
	var self = this;
	var layersProcessed = 0;

	// Block calls to this method if initialisation is already in progress
	if (serialisedState && !this.initInProgress)
	{
		// Stop multiple calls to replaceState as controls are checked
		this.initInProgress = true;

		var selectedLayers = serialisedState.split(',');

		// Recursively process each layer in sequence, waiting for regeneration to occur each time
		var processLayerType = function(layerTypes)
		{
			if (layerTypes.length < 1)
			{
				self.initInProgress = false;
				BM.LoadingProgress.hide();
				if (callback)
					return callback(layersProcessed);
			}

			var layerType = layerTypes.pop();

			// TODO: Implement clustered layer or remove this code once old deep-link URLs have been updated
			if (layerType == BM.LayerType.contact.clustered)
				layerType = BM.LayerType.contact.individual;

			var layer = self.getLayer(layerType);
			if (layer)
			{
				layersProcessed++;

				// Layer is not currently enabled, so generate it and add to the map
				if (!layer.isChecked())
				{
					console.log('Processing layer type: ' + layerType);
					layer.check();
					layer.regenerate(function() {
						console.log('Generated layer: ' + layerType);
						layer.addToMap(false);
						processLayerType(layerTypes);
					}, false);
				}
				else
				{
					// Layer is already enabled, so do not add it again
					processLayerType(layerTypes);
				}
			}
			else
			{
				console.log('Warning: Invalid layer type specified: "' + layerType + '"');
				processLayerType(layerTypes);
			}
		};

		processLayerType(selectedLayers);
	}
	else if(this.initInProgress)
	{
		console.log('Warning: Multiple calls to LayerController.parseState() detected');
		if (callback)
			callback(0);
	}
};

