/**
 * Refreshes the layer by calling the regeneration function associated with it
 * @param {BM.LayerType} layerType
 * @param callback
 */
BM.LayerController.prototype.regenerateLayer = function(layerType, callback)
{
	var layer = this.getLayer(layerType);
	if (layer)
	{
		if (layer.isChecked())
		{
			layer.regenerate(function () {
				if (callback)
					return callback();
			}, true);
		}
	}

	if (callback)
		callback();
};

/**
 * Refreshes the selected layer in a single-choice group (must have LayerGroup.allowMultipleActiveLayers set to FALSE.
 * Method does nothing on if this property is TRUE (i.e. checkbox groups)
 * @param {BM.LayerType} groupType
 * @param [callback]
 */
BM.LayerController.prototype.regenerateSelectedLayerInGroup = function(groupType, callback)
{
	var layer = this.getSelectedLayerInGroup(groupType);
	if (layer)
	{
		layer.regenerate(function () {
			if (callback)
				callback();
		}, true);
	}
	else
	{
		if (callback)
			callback();
	}
};

/**
 * Regenerates all currently enabled layers
 * @param [callback]
 */
BM.LayerController.prototype.regenerateAllLayers = function(callback)
{
	var self = this;

	// Starts the recursive process by triggering the first layer in the current group to be processed
	var processGroup = function(groupIndex)
	{
		if (groupIndex >= self.layerGroups.length)
		{
			if (callback)
			{
				BM.LoadingProgress.hide();
				return callback();
			}
		}

		processLayer(groupIndex, self.layerGroups[groupIndex].layers, 0);
	};

	// Processes each layer in the current group
	var processLayer = function(groupIndex, layers, layerIndex)
	{
		if (layerIndex >= layers.length)
			return processGroup(groupIndex + 1);

		var layer = layers[layerIndex];
		layer.regenerate(function() {
			processLayer(groupIndex, layers, layerIndex + 1);
		}, false);
	};

	// Start recursion from the first group until all groups and layers have been processed
	processGroup(0);
};